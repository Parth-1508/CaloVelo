package com.calovelo.app.data.local.dao

import androidx.room.ColumnInfo
import androidx.room.Dao
import androidx.room.Query
import androidx.room.Upsert
import com.calovelo.app.data.local.entity.MealLogEntity
import kotlinx.coroutines.flow.Flow

/** Summed nutrients of a day's LOGGED meals. */
data class MacroTotalsRow(
    @ColumnInfo(name = "kcal") val kcal: Double,
    @ColumnInfo(name = "protein_g") val proteinG: Double,
    @ColumnInfo(name = "carbs_g") val carbsG: Double,
    @ColumnInfo(name = "fat_g") val fatG: Double,
    @ColumnInfo(name = "fiber_g") val fiberG: Double
)

@Dao
interface MealLogDao {

    @Upsert
    suspend fun upsert(meal: MealLogEntity)

    @Upsert
    suspend fun upsertAll(meals: List<MealLogEntity>)

    @Query("SELECT * FROM meal_log WHERE id = :id LIMIT 1")
    suspend fun getById(id: String): MealLogEntity?

    /** Every meal (logged and planned) of [epochDay], oldest first. */
    @Query("SELECT * FROM meal_log WHERE date_epoch_day = :epochDay ORDER BY timestamp ASC, id ASC")
    fun observeForDay(epochDay: Long): Flow<List<MealLogEntity>>

    @Query(
        "SELECT * FROM meal_log WHERE date_epoch_day = :epochDay AND status = '" +
            MealLogEntity.STATUS_LOGGED + "' ORDER BY timestamp ASC, id ASC"
    )
    fun observeLoggedForDay(epochDay: Long): Flow<List<MealLogEntity>>

    @Query(
        "SELECT * FROM meal_log WHERE date_epoch_day = :epochDay AND status = '" +
            MealLogEntity.STATUS_PLANNED + "' ORDER BY timestamp ASC, id ASC"
    )
    fun observePlannedForDay(epochDay: Long): Flow<List<MealLogEntity>>

    /** Running macro totals for eaten meals; planned meals are excluded. Always emits one row. */
    @Query(
        "SELECT COALESCE(SUM(kcal), 0.0) AS kcal, " +
            "COALESCE(SUM(protein_g), 0.0) AS protein_g, " +
            "COALESCE(SUM(carbs_g), 0.0) AS carbs_g, " +
            "COALESCE(SUM(fat_g), 0.0) AS fat_g, " +
            "COALESCE(SUM(fiber_g), 0.0) AS fiber_g " +
            "FROM meal_log WHERE date_epoch_day = :epochDay AND status = '" +
            MealLogEntity.STATUS_LOGGED + "'"
    )
    fun observeLoggedTotals(epochDay: Long): Flow<MacroTotalsRow>

    @Query("DELETE FROM meal_log WHERE id = :id")
    suspend fun deleteById(id: String)

    /** Removes the day's un-eaten plan generated by the auto-planner. Eaten meals are never touched. */
    @Query(
        "DELETE FROM meal_log WHERE date_epoch_day = :epochDay AND status = '" +
            MealLogEntity.STATUS_PLANNED + "' AND source = '" + MealLogEntity.SOURCE_AUTO_PLAN + "'"
    )
    suspend fun deleteAutoPlannedForDay(epochDay: Long): Int

    /** Flips a PLANNED row to LOGGED and stamps the time it was eaten. Returns rows changed (0 or 1). */
    @Query(
        "UPDATE meal_log SET status = '" + MealLogEntity.STATUS_LOGGED + "', timestamp = :eatenAtMillis " +
            "WHERE id = :id AND status = '" + MealLogEntity.STATUS_PLANNED + "'"
    )
    suspend fun markEaten(id: String, eatenAtMillis: Long): Int
}
